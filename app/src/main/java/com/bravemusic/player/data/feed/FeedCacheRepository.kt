package com.bravemusic.player.data.feed

import android.content.Context
import android.util.Log
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import org.json.JSONArray
import java.io.File

class FeedCacheRepository(private val context: Context) {

    private val cacheFile = File(context.filesDir, "home_feed_cache.json")

    /**
     * Instantly returns cached sections from disk, or fallback mixes if cache does not exist yet.
     */
    fun getCachedFeed(): List<FeedSection> {
        return try {
            if (cacheFile.exists()) {
                val jsonStr = cacheFile.readText()
                val parsed = parseFeedJson(jsonStr)
                if (parsed.isNotEmpty()) return parsed
            }
            getDefaultFallbackFeed()
        } catch (e: Exception) {
            Log.e(TAG, "Failed to read cached feed: ${e.message}")
            getDefaultFallbackFeed()
        }
    }

    /**
     * Saves updated feed JSON to disk cache asynchronously.
     */
    suspend fun saveFeedCache(jsonStr: String) = withContext(Dispatchers.IO) {
        try {
            cacheFile.writeText(jsonStr)
        } catch (e: Exception) {
            Log.e(TAG, "Failed to save feed cache: ${e.message}")
        }
    }

    /**
     * Parses JSON array generated by feed_extractor.js
     */
    fun parseFeedJson(jsonStr: String): List<FeedSection> {
        val list = mutableListOf<FeedSection>()
        try {
            val jsonArray = JSONArray(jsonStr)
            for (i in 0 until jsonArray.length()) {
                val secObj = jsonArray.getJSONObject(i)
                val secId = secObj.optString("id", "section_$i")
                val secTitle = secObj.optString("title", "Mix ${i + 1}")
                val itemsArray = secObj.optJSONArray("items") ?: continue

                val items = mutableListOf<MediaItem>()
                for (j in 0 until itemsArray.length()) {
                    val itemObj = itemsArray.getJSONObject(j)
                    val id = itemObj.optString("id", "${secId}_$j")
                    val title = itemObj.optString("title", "")
                    val subtitle = itemObj.optString("subtitle", "")
                    val thumbnailUrl = itemObj.optString("thumbnailUrl", "")
                    val videoId = itemObj.optString("videoId", "").takeIf { it.isNotBlank() }
                    val playlistId = itemObj.optString("playlistId", "").takeIf { it.isNotBlank() }

                    if (title.isNotBlank()) {
                        items.add(
                            MediaItem(
                                id = id,
                                title = title,
                                subtitle = subtitle,
                                thumbnailUrl = thumbnailUrl,
                                videoId = videoId,
                                playlistId = playlistId
                            )
                        )
                    }
                }

                if (items.isNotEmpty()) {
                    list.add(FeedSection(id = secId, title = secTitle, items = items))
                }
            }
        } catch (e: Exception) {
            Log.e(TAG, "Error parsing feed JSON: ${e.message}")
        }
        return list
    }

